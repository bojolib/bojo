package apidoc

import (
	"fmt"
	"sort"
	"strings"
)

// Meta carries optional package metadata used when rendering API.md.
type Meta struct {
	ModulePath  string // e.g. "gh.bojolib.socket" or "v2.gh.bojolib.socket"
	RepoURL     string // e.g. "https://github.com/bojolib/socket"
	Description string // fallback summary when doc.Decl.Summary is empty
}

// RenderMarkdown renders a deterministic, human- and agent-readable API.md
// from a parsed Mojo Doc. Output contains zero timestamps or host paths.
func RenderMarkdown(doc *Doc, meta Meta) string {
	var b strings.Builder

	title := strings.TrimSpace(meta.ModulePath)
	if title == "" && doc != nil {
		title = strings.TrimSpace(doc.Decl.Name)
	}
	if title == "" {
		title = "API Reference"
	}

	b.WriteString("# ")
	b.WriteString(title)
	b.WriteString("\n\n")
	b.WriteString("> Generated by `bojo lib api` — do not edit by hand.\n")

	if doc == nil {
		return b.String()
	}

	views := FlattenPublic(doc)

	summary := strings.TrimSpace(doc.Decl.Summary)
	description := strings.TrimSpace(doc.Decl.Description)
	if summary == "" && description == "" {
		summary = strings.TrimSpace(meta.Description)
	}
	writeDocText(&b, summary, description)

	multiModule := false
	for _, v := range views {
		if v.Path != "" {
			multiModule = true
			break
		}
	}

	for _, v := range views {
		if !hasPublicContent(v) {
			continue
		}

		sectionLevel := 2
		if v.Path != "" {
			b.WriteString("\n## Module `")
			b.WriteString(v.Path)
			b.WriteString("`\n")
			writeDocText(&b, v.Summary, v.Description)
			sectionLevel = 3
		} else if multiModule {
			b.WriteString("\n## Package Exports\n")
			sectionLevel = 3
		}

		if len(v.Aliases) > 0 {
			writeHeading(&b, sectionLevel, "Aliases")
			for _, a := range v.Aliases {
				renderAlias(&b, sectionLevel+1, a)
			}
		}

		if len(v.Traits) > 0 {
			writeHeading(&b, sectionLevel, "Traits")
			for _, t := range v.Traits {
				renderTrait(&b, sectionLevel+1, t)
			}
		}

		if len(v.Structs) > 0 {
			writeHeading(&b, sectionLevel, "Structs")
			for _, s := range v.Structs {
				renderStruct(&b, sectionLevel+1, s)
			}
		}

		if len(v.Functions) > 0 {
			writeHeading(&b, sectionLevel, "Functions")
			for _, fn := range v.Functions {
				renderFunction(&b, sectionLevel+1, fn)
			}
		}
	}

	return strings.TrimRight(b.String(), "\n") + "\n"
}

func hasPublicContent(v ModuleView) bool {
	return len(v.Aliases) > 0 || len(v.Traits) > 0 || len(v.Structs) > 0 || len(v.Functions) > 0
}

func writeHeading(b *strings.Builder, level int, title string) {
	if level > 6 {
		level = 6
	}
	b.WriteString("\n")
	b.WriteString(strings.Repeat("#", level))
	b.WriteString(" ")
	b.WriteString(title)
	b.WriteString("\n")
}

func writeDocText(b *strings.Builder, summary, description string) {
	summary = normalizeText(summary)
	description = normalizeText(description)
	if summary != "" {
		b.WriteString("\n")
		b.WriteString(summary)
		b.WriteString("\n")
	}
	if description != "" && description != summary {
		b.WriteString("\n")
		b.WriteString(description)
		b.WriteString("\n")
	}
}

func writeCodeFence(b *strings.Builder, sig string) {
	sig = normalizeText(sig)
	if sig == "" {
		return
	}
	b.WriteString("\n```mojo\n")
	b.WriteString(sig)
	b.WriteString("\n```\n")
}

func renderAlias(b *strings.Builder, level int, a Alias) {
	writeHeading(b, level, "`"+a.Name+"`")
	if dep := normalizeText(a.Deprecated); dep != "" {
		fmt.Fprintf(b, "\n> **Deprecated:** %s\n", dep)
	}
	writeCodeFence(b, AliasSignature(a))
	writeDocText(b, a.Summary, a.Description)
}

func renderTrait(b *strings.Builder, level int, t Trait) {
	writeHeading(b, level, "`"+t.Name+"`")
	if dep := normalizeText(t.Deprecated); dep != "" {
		fmt.Fprintf(b, "\n> **Deprecated:** %s\n", dep)
	}
	writeCodeFence(b, TraitSignature(t))
	writeDocText(b, t.Summary, t.Description)

	if len(t.Aliases) > 0 {
		writeHeading(b, level+1, "Associated Aliases")
		for _, a := range t.Aliases {
			renderAlias(b, level+2, a)
		}
	}
	if len(t.Functions) > 0 {
		writeHeading(b, level+1, "Methods")
		for _, fn := range t.Functions {
			renderFunction(b, level+2, fn)
		}
	}
}

func renderStruct(b *strings.Builder, level int, s Struct) {
	writeHeading(b, level, "`"+s.Name+"`")
	if dep := normalizeText(s.Deprecated); dep != "" {
		fmt.Fprintf(b, "\n> **Deprecated:** %s\n", dep)
	}
	writeCodeFence(b, StructSignature(s))
	writeDocText(b, s.Summary, s.Description)

	if len(s.Parameters) > 0 {
		b.WriteString("\n**Parameters:**\n\n")
		for _, p := range s.Parameters {
			writeParamBullet(b, p)
		}
	}

	if len(s.Fields) > 0 {
		b.WriteString("\n**Fields:**\n\n")
		for _, f := range s.Fields {
			fmt.Fprintf(b, "- `%s`", f.Name)
			if f.Type != "" {
				fmt.Fprintf(b, " (`%s`)", f.Type)
			}
			desc := firstNonEmpty(f.Summary, f.Description)
			if desc != "" {
				fmt.Fprintf(b, ": %s", desc)
			}
			if f.Deprecated != "" {
				fmt.Fprintf(b, " *(Deprecated: %s)*", normalizeText(f.Deprecated))
			}
			b.WriteString("\n")
		}
	}

	if len(s.Aliases) > 0 {
		writeHeading(b, level+1, "Aliases")
		for _, a := range s.Aliases {
			renderAlias(b, level+2, a)
		}
	}
	if len(s.Functions) > 0 {
		writeHeading(b, level+1, "Methods")
		for _, fn := range s.Functions {
			renderFunction(b, level+2, fn)
		}
	}
}

func renderFunction(b *strings.Builder, level int, fn Function) {
	writeHeading(b, level, "`"+fn.Name+"`")
	if len(fn.Overloads) == 0 {
		writeCodeFence(b, "def "+fn.Name+"()")
		return
	}
	for _, ov := range fn.Overloads {
		if dep := normalizeText(ov.Deprecated); dep != "" {
			fmt.Fprintf(b, "\n> **Deprecated:** %s\n", dep)
		}
		writeCodeFence(b, OverloadSignature(fn.Name, ov))
		writeDocText(b, ov.Summary, ov.Description)

		if len(ov.Parameters) > 0 {
			b.WriteString("\n**Parameters:**\n\n")
			for _, p := range ov.Parameters {
				writeParamBullet(b, p)
			}
		}
		if len(ov.Args) > 0 {
			b.WriteString("\n**Args:**\n\n")
			for _, a := range ov.Args {
				fmt.Fprintf(b, "- `%s`", a.Name)
				if a.Type != "" {
					if a.Convention != "" && a.Convention != "imm" && a.Convention != "read" {
						fmt.Fprintf(b, " (`%s %s`)", a.Convention, a.Type)
					} else {
						fmt.Fprintf(b, " (`%s`)", a.Type)
					}
				}
				if a.Default != "" {
					fmt.Fprintf(b, " = `%s`", a.Default)
				}
				if desc := normalizeText(a.Description); desc != "" {
					fmt.Fprintf(b, ": %s", desc)
				}
				b.WriteString("\n")
			}
		}
		if ov.Returns != nil && (ov.Returns.Type != "" || ov.Returns.Doc != "" || ov.ReturnsDoc != "") {
			retDoc := firstNonEmpty(ov.Returns.Doc, ov.ReturnsDoc)
			b.WriteString("\n**Returns:** ")
			if ov.Returns.Type != "" {
				fmt.Fprintf(b, "`%s`", ov.Returns.Type)
				if retDoc != "" {
					fmt.Fprintf(b, " — %s", retDoc)
				}
			} else {
				b.WriteString(retDoc)
			}
			b.WriteString("\n")
		} else if retDoc := normalizeText(ov.ReturnsDoc); retDoc != "" {
			fmt.Fprintf(b, "\n**Returns:** %s\n", retDoc)
		}
		if ov.Raises || normalizeText(ov.RaisesDoc) != "" {
			if rdoc := normalizeText(ov.RaisesDoc); rdoc != "" {
				fmt.Fprintf(b, "\n**Raises:** %s\n", rdoc)
			} else {
				b.WriteString("\n**Raises:** Yes\n")
			}
		}
	}
}

func writeParamBullet(b *strings.Builder, p Param) {
	fmt.Fprintf(b, "- `%s`", p.Name)
	if p.Type != "" {
		fmt.Fprintf(b, " (`%s`)", p.Type)
	}
	if p.Default != "" {
		fmt.Fprintf(b, " = `%s`", p.Default)
	}
	if desc := normalizeText(p.Description); desc != "" {
		fmt.Fprintf(b, ": %s", desc)
	}
	b.WriteString("\n")
}

// AliasSignature returns the canonical signature string for an Alias.
func AliasSignature(a Alias) string {
	if s := normalizeText(a.Signature); s != "" {
		return s
	}
	if v := normalizeText(a.Value); v != "" {
		return fmt.Sprintf("alias %s = %s", a.Name, v)
	}
	return fmt.Sprintf("alias %s", a.Name)
}

// StructSignature returns the canonical signature string for a Struct.
func StructSignature(s Struct) string {
	if sig := normalizeText(s.Signature); sig != "" {
		return sig
	}
	var b strings.Builder
	b.WriteString("struct ")
	b.WriteString(s.Name)
	if len(s.Parameters) > 0 {
		b.WriteString("[")
		for i, p := range s.Parameters {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(formatParam(p))
		}
		b.WriteString("]")
	}
	if len(s.ParentTraits) > 0 {
		b.WriteString("(")
		b.WriteString(strings.Join(s.ParentTraits, ", "))
		b.WriteString(")")
	}
	return b.String()
}

// TraitSignature returns the canonical signature string for a Trait.
func TraitSignature(t Trait) string {
	if sig := normalizeText(t.Signature); sig != "" {
		return sig
	}
	if len(t.ParentTraits) > 0 {
		return fmt.Sprintf("trait %s(%s)", t.Name, strings.Join(t.ParentTraits, ", "))
	}
	return "trait " + t.Name
}

// OverloadSignature returns the canonical signature string for a Function Overload.
func OverloadSignature(fallbackName string, ov Overload) string {
	if sig := normalizeText(ov.Signature); sig != "" {
		return sig
	}
	name := ov.Name
	if name == "" {
		name = fallbackName
	}
	var b strings.Builder
	if ov.Async {
		b.WriteString("async ")
	}
	b.WriteString("def ")
	b.WriteString(name)
	if len(ov.Parameters) > 0 {
		b.WriteString("[")
		for i, p := range ov.Parameters {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(formatParam(p))
		}
		b.WriteString("]")
	}
	b.WriteString("(")
	for i, a := range ov.Args {
		if i > 0 {
			b.WriteString(", ")
		}
		if a.Convention != "" && a.Convention != "imm" && a.Convention != "read" {
			b.WriteString(a.Convention)
			b.WriteString(" ")
		}
		b.WriteString(a.Name)
		if a.Type != "" {
			b.WriteString(": ")
			b.WriteString(a.Type)
		}
		if a.Default != "" {
			b.WriteString(" = ")
			b.WriteString(a.Default)
		}
	}
	b.WriteString(")")
	if ov.Raises {
		b.WriteString(" raises")
	}
	if ov.Returns != nil && ov.Returns.Type != "" {
		b.WriteString(" -> ")
		b.WriteString(ov.Returns.Type)
	}
	return b.String()
}

func formatParam(p Param) string {
	var b strings.Builder
	b.WriteString(p.Name)
	if p.Type != "" {
		b.WriteString(": ")
		b.WriteString(p.Type)
	}
	if p.Default != "" {
		b.WriteString(" = ")
		b.WriteString(p.Default)
	}
	return b.String()
}

func normalizeText(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	lines := strings.Split(strings.TrimSpace(s), "\n")
	for i, l := range lines {
		lines[i] = strings.TrimRight(l, " \t")
	}
	return strings.TrimSpace(strings.Join(lines, "\n"))
}

func firstNonEmpty(a, b string) string {
	if s := normalizeText(a); s != "" {
		return s
	}
	return normalizeText(b)
}

func sortModuleViews(views []ModuleView) {
	sort.SliceStable(views, func(i, j int) bool {
		if views[i].Path == "" && views[j].Path != "" {
			return true
		}
		if views[i].Path != "" && views[j].Path == "" {
			return false
		}
		return views[i].Path < views[j].Path
	})
}

func sortModuleView(v *ModuleView) {
	sortAliases(v.Aliases)
	sortTraits(v.Traits)
	sortStructs(v.Structs)
	sortFunctions(v.Functions)
}

func sortAliases(in []Alias) {
	sort.Slice(in, func(i, j int) bool { return in[i].Name < in[j].Name })
}

func sortFields(in []Field) {
	sort.Slice(in, func(i, j int) bool { return in[i].Name < in[j].Name })
}

func sortFunctions(in []Function) {
	sort.Slice(in, func(i, j int) bool { return in[i].Name < in[j].Name })
	for idx := range in {
		ovs := in[idx].Overloads
		name := in[idx].Name
		sort.Slice(ovs, func(i, j int) bool {
			return OverloadSignature(name, ovs[i]) < OverloadSignature(name, ovs[j])
		})
	}
}

func sortStructs(in []Struct) {
	sort.Slice(in, func(i, j int) bool { return in[i].Name < in[j].Name })
	for idx := range in {
		sortFields(in[idx].Fields)
		sortAliases(in[idx].Aliases)
		sortFunctions(in[idx].Functions)
		sort.Strings(in[idx].ParentTraits)
	}
}

func sortTraits(in []Trait) {
	sort.Slice(in, func(i, j int) bool { return in[i].Name < in[j].Name })
	for idx := range in {
		sortAliases(in[idx].Aliases)
		sortFunctions(in[idx].Functions)
		sort.Strings(in[idx].ParentTraits)
	}
}
