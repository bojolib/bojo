const assetAppJS = `(function () {
  var root = document.body.getAttribute('data-root') || '';

  // Theme toggle
  var toggle = document.getElementById('theme-toggle');
  if (toggle) {
    toggle.addEventListener('click', function () {
      var cur = document.documentElement.getAttribute('data-theme');
      var next = cur === 'dark' ? 'light' : 'dark';
      if (next === 'dark') {
        document.documentElement.setAttribute('data-theme', 'dark');
      } else {
        document.documentElement.removeAttribute('data-theme');
      }
      try { localStorage.setItem('bojo-theme', next); } catch (e) {}
    });
  }

  // Copy buttons
  document.addEventListener('click', function (ev) {
    var btn = ev.target.closest('.copy-btn');
    if (!btn) return;
    var text = btn.getAttribute('data-copy-text') || '';
    var targetId = btn.getAttribute('data-copy-target');
    if (targetId) {
      var el = document.getElementById(targetId);
      if (el) text = el.textContent || '';
    }
    if (!text) return;
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(function () {
        var old = btn.textContent;
        btn.textContent = 'Copied';
        setTimeout(function () { btn.textContent = old; }, 1200);
      });
    }
  });

  // Client-side search
  var input = document.getElementById('search-input');
  var box = document.getElementById('search-results');
  var indexData = null;

  function loadIndex(cb) {
    if (indexData !== null) { cb(indexData); return; }
    fetch(root + 'search.json')
      .then(function (r) { return r.ok ? r.json() : []; })
      .then(function (data) { indexData = Array.isArray(data) ? data : []; cb(indexData); })
      .catch(function () { indexData = []; cb(indexData); });
  }

  function renderResults(items) {
    if (!box) return;
    while (box.firstChild) box.removeChild(box.firstChild);
    if (!items.length) {
      box.hidden = true;
      return;
    }
    items.slice(0, 12).forEach(function (item) {
      var a = document.createElement('a');
      a.className = 'search-item';
      a.href = root + item.url;

      var head = document.createElement('div');
      head.className = 'search-item-head';
      var pill = document.createElement('span');
      pill.className = 'kind-pill';
      pill.textContent = item.kind || 'doc';
      var title = document.createElement('span');
      title.textContent = item.title || '';
      head.appendChild(pill);
      head.appendChild(title);
      a.appendChild(head);

      var metaText = [item.module, item.summary].filter(Boolean).join(' — ');
      if (metaText) {
        var meta = document.createElement('div');
        meta.className = 'search-item-meta';
        meta.textContent = metaText;
        a.appendChild(meta);
      }
      box.appendChild(a);
    });
    box.hidden = false;
  }

  if (input && box) {
    input.addEventListener('input', function () {
      var q = input.value.trim().toLowerCase();
      if (!q) { box.hidden = true; return; }
      loadIndex(function (entries) {
        var hits = entries.filter(function (e) {
          var hay = ((e.title || '') + ' ' + (e.module || '') + ' ' + (e.summary || '') + ' ' + (e.kind || '')).toLowerCase();
          return hay.indexOf(q) !== -1;
        });
        renderResults(hits);
      });
    });

    document.addEventListener('click', function (ev) {
      if (!ev.target.closest('.search-box')) {
        box.hidden = true;
      }
    });

    document.addEventListener('keydown', function (ev) {
      if (ev.key === '/' && document.activeElement !== input &&
          !/INPUT|TEXTAREA/.test((document.activeElement && document.activeElement.tagName) || '')) {
        ev.preventDefault();
        input.focus();
      } else if (ev.key === 'Escape') {
        box.hidden = true;
        input.blur();
      }
    });
  }
})();
`
